## Probe: residual bias and benchmark coverage by cell, 200 replicates; cost.
source("R/00-model.R")
g <- build_grid(); set.seed(1); t0 <- proc.time()[["elapsed"]]
rows <- do.call(rbind, lapply(seq_len(nrow(g)), function(i) { cc <- g[i, ]; tr <- truths(cc); r <- t(replicate(200, fit_all(cc, draw(cc))))
  cv <- function(k) mean(abs(tr[["bias"]]) <= r[, k])
  data.frame(q = cc$q, rho = cc$rho, s = cc$s, bias = tr[["bias"]], benchmark = stats::median(r[, "benchmark"]),
             plain = cv("benchmark"), sqrt_q = cv("scaled"), oracle = cv("scaled_oracle"), linear = cv("scaled_linear")) }))
sec <- (proc.time()[["elapsed"]] - t0) / (200 * nrow(g))
md <- c("# QBA-26 probes", "", "Generated by `R/01-probes.R`, 200 replicates per cell. Coverage: share of analyses whose benchmark is at least the true residual bias.", "",
  "| q | rho | s | true residual bias | median benchmark | plain | times sqrt(q) | oracle | times q |", "|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
  sprintf("| %d | %.1f | %.1f | %.3f | %.3f | %.2f | %.2f | %.2f | %.2f |", rows$q, rows$rho, rows$s, rows$bias, rows$benchmark, rows$plain, rows$sqrt_q, rows$oracle, rows$linear), "",
  sprintf("Unit cost %.3f s per replicate; %d cells at %d replicates is %.2f core-hours.", sec, nrow(g), N_SIM, nrow(g) * N_SIM * sec / 3600), "")
writeLines(md, "results/probes.md"); cat(md, sep = "\n")
