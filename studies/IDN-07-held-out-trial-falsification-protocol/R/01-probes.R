## Probe: null size of each rule, E[D] with and without an external target, cost.
source("R/00-model.R")
g <- build_grid(); set.seed(2); t0 <- proc.time()[["elapsed"]]
rows <- do.call(rbind, lapply(which(g$v == 0), function(i) { cc <- g[i, ]; r <- t(replicate(400, fit_all(cc, draw(cc))))
  data.frame(tau = cc$tau, s = cc$s, held = cc$held, size_full = mean(abs(r[, "z_full"]) > 1.96), size_naive = mean(abs(r[, "z_naive"]) > 1.96),
             size_wrong_target = mean(abs(r[, "z_wrong_target"]) > 1.96), mean_D = mean(r[, "D"]), mean_D_wrong = mean(r[, "D_wrong"]),
             var_D = stats::var(r[, "D"]), mean_full_var = mean(r[, "v_pred"] + r[, "v_obs"] + r[, "tau2"])) }))
sec <- (proc.time()[["elapsed"]] - t0) / (400 * nrow(rows))
md <- c("# IDN-07 probes", "", "Generated by `R/01-probes.R`. No violation, 400 replicates per cell.", "",
  paste("|", paste(names(rows), collapse = " | "), "|"), paste(rep("|---:", ncol(rows)), collapse = ""),
  apply(round(rows, 4), 1, function(r) paste("|", paste(r, collapse = " | "), "|")), "",
  sprintf("Unit cost %.4f s per replicate; %d cells at %d replicates is %.2f core-hours.", sec, nrow(g), N_SIM, nrow(g) * N_SIM * sec / 3600), "")
writeLines(md, "results/probes.md"); cat(md, sep = "\n")
