## Probes: truths and analytic omitted-covariate bias (P1); the frequentist arms in
## every cell (50 replicates: null control, witness against mlumr::stc); one
## mlumr smoke fit (1 chain, 400 iterations), timed. Writes results/probes.md.
source("R/00-model.R"); g <- build_grid()
out <- c("# SFW-13 probes", "", sprintf("Generated by `R/01-probes.R`; mlumr %s (RemoteSha %s), rstan %s.", utils::packageVersion("mlumr"),
  substr(utils::packageDescription("mlumr")$RemoteSha, 1, 7), utils::packageVersion("rstan")), "")

tr <- do.call(rbind, lapply(seq_len(nrow(g)), function(i) data.frame(g[i, ], t(truth(g[i, ])))))
out <- c(out, "## P1 truths and analytic bias of the SPFA estimate (u omitted)", "", "| BU | comparator x1 mean | pA | pB | LOR | analytic bias pA | analytic bias LOR |", "|---:|---:|---:|---:|---:|---:|---:|",
  sprintf("| %.2f | %.1f | %.4f | %.4f | %.4f | %.4f | %.4f |", tr$bu, tr$m1, tr$pA, tr$pB, tr$lor, tr$bias_pA, tr$bias_lor), "")

t0 <- proc.time()[["user.self"]]
fr <- do.call(rbind, lapply(seq_len(nrow(g)), function(i) { cc <- g[i, ]
  r <- do.call(rbind, lapply(1:50, function(k) { set.seed(1000 * i + k); z <- one_rep(cc, seed = 1, stan = FALSE); z$rep <- k; z })); r$cell <- cc$cell; r }))
sec_free <- (proc.time()[["user.self"]] - t0) / (50 * nrow(g))
fr <- merge(fr, tr[, c("cell", "bu", "m1", "pA")], by = "cell", suffixes = c("", "_true"))
fs <- do.call(rbind, lapply(split(fr, list(fr$cell, fr$method), drop = TRUE), function(z) data.frame(bu = z$bu[1], m1 = z$m1[1], method = z$method[1],
  failed = sum(is.na(z$pA)), bias = mean(z$pA - z$pA_true, na.rm = TRUE), coverage = mean(z$lo <= z$pA_true & z$pA_true <= z$hi, na.rm = TRUE))))
fs <- fs[order(fs$bu, fs$m1, fs$method), ]
ws <- merge(fr[fr$method == "witness", c("cell", "rep", "pA")], fr[fr$method == "stc", c("cell", "rep", "pA")], by = c("cell", "rep"))
out <- c(out, "## Frequentist arms, 50 replicates per cell", "", "| BU | comparator x1 mean | method | failed | bias pA | coverage pA |", "|---:|---:|---|---:|---:|---:|",
  sprintf("| %.2f | %.1f | %s | %d | %.4f | %.2f |", fs$bu, fs$m1, fs$method, fs$failed, fs$bias, fs$coverage), "",
  sprintf("Witness against mlumr::stc, same datasets: largest absolute difference in pA %.1e.", max(abs(ws$pA.x - ws$pA.y))), "",
  sprintf("Frequentist arms: %.3f CPU s per replicate.", sec_free), "")

## P2 integration error: mlumr::stc (mlumr's integration points) minus the witness (exact quadrature),
## same data, by n_int; 10 datasets, cell 4.
ni <- c(64, 128, 256, 512, 1024)
ie <- do.call(rbind, lapply(1:10, function(k) { set.seed(k); d <- draw(g[4, ]); w <- witness(d)[["pA"]]
  vapply(ni, function(n) { N_INT <<- n; stc(as_mlumr(d))$p_hat_index - w }, 0) })); N_INT <- 256L
out <- c(out, "## P2 integration error of mlumr's points (stc minus witness, pA, 10 datasets, cell 4)", "", "| n_int | mean | min | max |", "|---:|---:|---:|---:|",
  sprintf("| %d | %.4f | %.4f | %.4f |", ni, colMeans(ie), apply(ie, 2, min), apply(ie, 2, max)), "",
  "The error has one sign in every dataset (the point set is deterministic), so at the default 64 points it is a fixed offset, not noise. The registered run uses 256.", "")

## One Stan smoke fit, null cell, timed.
set.seed(7); cc <- g[1, ]; d <- draw(cc); dat <- as_mlumr(d); w <- witness(d)
t1 <- proc.time(); sm <- tryCatch(fit_mlumr(dat, seed = 7L, chains = 1L, iter = 400L), error = function(e) fail("mlumr", e)); t2 <- proc.time() - t1
cpu <- t2[["user.self"]] + t2[["sys.self"]]; ext <- cpu * (CHAINS * ITER) / 400
out <- c(out, "## mlumr smoke fit (null cell, 1 chain, 400 iterations)", "",
  if (!is.na(sm$error)) paste("- failed:", sm$error) else c(
  sprintf("- pA %.4f (posterior SD %.4f), witness %.4f: difference %.2f posterior SD.", sm$pA, sm$se_pA, w[["pA"]], abs(sm$pA - w[["pA"]]) / sm$se_pA),
  sprintf("- IPD population: posterior mean %.4f against the IPD proportion %.4f.", sm$pA_index, mean(d$ipd$y)),
  sprintf("- max Rhat %.3f, divergent transitions %d.", sm$max_rhat, as.integer(sm$n_divergent))),
  sprintf("- %.1f CPU s (%.1f s elapsed) for 400 iterations; extrapolated to %d chains x %d iterations: %.0f CPU s per fit (linear in iterations, from one fit at about 13%% CPU share).", cpu, t2[["elapsed"]], CHAINS, ITER, ext),
  sprintf("- Registered run: %d cells x %d replicates x (%.0f + %.1f) CPU s = %.1f CPU hours.", nrow(g), N_SIM, ext, sec_free, nrow(g) * N_SIM * (ext + sec_free) / 3600), "")
writeLines(out, "results/probes.md"); cat(out, sep = "\n")
