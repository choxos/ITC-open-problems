## P1 null control, P2 weight feasibility (covariates only), P3 semi-synthetic truth
## recovery, P4 unit cost. No main-unit discrepancy on the real outcomes is computed.
## Writes results/probes.md.   nice -n 19 Rscript R/01-probes.R
source("R/00-model.R"); g <- build_grid(); set.seed(1)
out <- c("# Probes", "", "Generated by `R/01-probes.R`. No main-unit discrepancy on the real outcomes is computed here.", "")

## P1: S = M. Bucher must reproduce the reference and both arms exactly, in the
## point estimate and in every bootstrap draw; MAIC must sit near zero.
p1 <- lapply(g$unit[g$kind == "self"], function(k) one_unit(g[g$unit == k, ], n_boot = 20))
out <- c(out, "## P1 null control (self units, 20 bootstrap draws each)", "",
  sprintf("- unit %d (%s, %s): max |Bucher discrepancy| over point and draws %.1e; MAIC relative z %.2f",
          vapply(p1, function(r) r$unit$unit, 0L), vapply(p1, function(r) r$unit$M, ""), vapply(p1, function(r) r$unit$A, ""),
          vapply(p1, function(r) max(abs(c(r$point[c("rel_bucher", "armA_bucher", "armC_bucher")], r$boot[, c("rel_bucher", "armA_bucher", "armC_bucher")]))), 0),
          vapply(p1, function(r) r$point[["rel_maic"]] / rse(r$boot[, "rel_maic"]), 0)), "")

## P2: MAIC on covariates only: effective sample share and worst standardized imbalance after weighting.
p2 <- do.call(rbind, lapply(seq_len(nrow(g)), function(i) { dd <- unit_data(g[i, ]); x <- as.matrix(dd$ds[, X]); tg <- colMeans(dd$dm[dd$dm$trt %in% c("ETN", "PBO"), X])
  w <- maic_w(x, tg); data.frame(unit = g$unit[i], kind = g$kind[i], nS = nrow(x), ess = sum(w)^2 / sum(w^2) / length(w), bal = max(abs(colSums(w * x) / sum(w) - tg) / apply(x, 2, stats::sd))) }))
out <- c(out, "## P2 weight feasibility (covariates only)", "", "| unit | kind | n in S | ESS share | max standardized imbalance after weighting |", "|---:|---|---:|---:|---:|",
  sprintf("| %d | %s | %d | %.3f | %.1e |", p2$unit, p2$kind, p2$nS, p2$ess, p2$bal), "")

## P3: outcomes regenerated from one logistic model with no study effect and no
## modification (weight prognostic): every discrepancy has mean zero.
u <- g[1, ]; dd <- unit_data(u)
sim_y <- function(d) stats::rbinom(nrow(d), 1, stats::plogis(-2.6 - 0.02 * (d$weight - 90) + 4.8 * (d$trt == u$A) + 2.6 * (d$trt == "ETN")))
p3 <- t(replicate(40, { ds <- dd$ds; dm <- dd$dm; ds$y <- sim_y(ds); dm$y <- sim_y(dm); stats_one(ds, dm, u$A) }))
k3 <- c("rel_bucher", "rel_maic", "rel_stc_marg", "armA_maic", "armC_maic", "gap_rd")
out <- c(out, sprintf("## P3 semi-synthetic truth recovery (unit %d design, 40 outcome draws)", u$unit), "",
  sprintf("- %s: mean %.3f (MCSE %.3f)", k3, colMeans(p3[, k3]), apply(p3[, k3], 2, stats::sd) / sqrt(nrow(p3))), "")

## P5: positive control (semi-synthetic baseline shift), 100 bootstrap draws.
p5 <- lapply(g$unit[g$kind == "pos"], function(k) one_unit(g[g$unit == k, ], n_boot = 100))
zz <- function(r, s) r$point[[s]] / rse(r$boot[, s])
out <- c(out, sprintf("## P5 positive control (M's outcomes regenerated with a %g logit baseline shift, 100 bootstrap draws)", DELTA), "",
  sprintf("- unit %d (M %s): MAIC relative z %.2f, arm A z %.2f, arm PBO z %.2f; discordant %s",
          vapply(p5, function(r) r$unit$unit, 0L), vapply(p5, function(r) r$unit$M, ""), vapply(p5, zz, 0, "rel_maic"), vapply(p5, zz, 0, "armA_maic"), vapply(p5, zz, 0, "armC_maic"),
          vapply(p5, function(r) abs(zz(r, "rel_maic")) <= 1.96 && max(abs(zz(r, "armA_maic")), abs(zz(r, "armC_maic"))) > 2.24, TRUE)),
  "- Before this control was adopted, M restricted to weight >= 100 kg was probed on the real outcomes: Bucher arm-A z -0.52 and 0.56, so it could not fire and was replaced.", "")

## P4: unit cost of one bootstrap draw on a main unit (values discarded).
tm <- system.time(invisible(one_unit(u, n_boot = 10)))
per <- tm[["user.self"]] / 11; tot <- nrow(g) * (N_BOOT + 1) * per
out <- c(out, "## P4 unit cost", "", sprintf("- CPU per pipeline evaluation %.3f s (elapsed %.1f s for 11 on a heavily loaded shared machine)", per, tm[["elapsed"]]),
  sprintf("- registered run: %d units x %d bootstrap draws, about %.2f CPU hours", nrow(g), N_BOOT, tot / 3600), "")
writeLines(out, "results/probes.md"); cat(out, sep = "\n")
